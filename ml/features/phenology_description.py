"""Phenology semantic branch via description + text-encoder (US-022b-D).

Implements the Wen et al. (2025) "Phenology description is all you
need!" method §3.2-3.3: given a parcel's temporal NDVI curve, it produces
a structured textual description with an LLM and encodes it with a
text-encoder into a dense vector that is concatenated to the baseline's
tabular vector.

The generator uses **Gemini 3.5 Flash** (ADR-006 D4, decision approved by
the team) via Vertex AI / LiteLLM (no new ``google-genai`` SDK). The
default text-encoder is ``sentence-transformers`` (already in deps); the
FarSLIP CLIP text-encoder remains a documented alternative (not
implemented here — owned by US-017).

Canonical decisions (plan ``docs/us-planning/us-022b.md`` §6.3):

- **D-ARQ-3**: the semantic branch is a **model component**, not a trivial
  FE column. Its own module + cache + tests.
- **D-ARQ-5**: Gemini is invoked via ``litellm`` (already in deps) which
  routes to Vertex AI. No new ``google-genai`` SDK.
- **R7 mitigated**: ``temperature=0`` + cache per ``parcel_id`` + stratified
  subset mandatory. The test suite mocks Gemini in CI (zero network
  calls).
- **Module output**: ``pl.DataFrame`` with ``parcel_id`` + N
  ``pheno_text_NNN`` columns; the block enters ``fusion.py`` via LEFT JOIN.

3-block prompt (Wen Fig. 2):
  1. **General**: problem description and expected format.
  2. **Time-Series Curve**: the NDVI values and days of the year.
  3. **Restrictive Instruction**: structured output, no extra text.
"""

