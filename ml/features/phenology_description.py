@dataclass(frozen=True)
class PhenologyDescription:
    """Phenology description of a parcel + its embedding.

    Attributes:
        parcel_id: Parcel identifier (accepts int or string).
        description: Text generated by the LLM (no control characters).
        embedding: Dense text-encoder vector (shape ``(D,)``).
        crop_type_hint: Crop hint supplied to the prompt (may be
            ``None``).
    """

    parcel_id: int | str
    description: str
    embedding: list[float]
    crop_type_hint: str | None


def default_cache_dir() -> Path:
    """Default directory for the descriptions cache (DVC-friendly).

    Returns:
        ``data/cache/phenology_descriptions/`` (creates the directory if it
        does not exist; ``.gitignore`` excludes it except the manifest).
    """
    repo_root = Path(__file__).resolve().parents[2]
    cache = repo_root / "data" / "cache" / "phenology_descriptions"
    cache.mkdir(parents=True, exist_ok=True)
    return cache


