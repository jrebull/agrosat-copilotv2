def generate_phenology_description(
    ndvi_curve: np.ndarray,
    doy: np.ndarray | None = None,
    *,
    parcel_id: int | str | None = None,
    crop_type_hint: str | None = None,
    model: str = "gemini-3.5-flash",
    temperature: float = 0.0,
    cache_dir: Path | None = None,
) -> str:
    """Generate the textual phenology description of a parcel.

    Implements the 3-block prompt from Wen et al. (2025) Fig. 2:
    General + Time-Series Curve + Restrictive Instruction.

    Args:
        ndvi_curve: NDVI vector ``(T,)`` (interpolated daily curve or
            regular sampling). Accepts NaN; replaces them with the local
            mean before serializing.
        doy: Day-of-year vector ``(T,)`` (1..366). If ``None`` an
            equally spaced grid ``linspace(1, 365, T)`` is assumed.
        parcel_id: Used to name the cache file. If ``None`` the
            description is not cached (ad-hoc use).
        crop_type_hint: Optional hint ("trigo", "maiz", "viñedo", ...)
            that enters block 2 of the prompt.
        model: Model identifier (default ``"gemini-3.5-flash"``).
            LiteLLM routes to Vertex AI; other OpenAI-compatible values
            also work.
        temperature: Sampling temperature. **Default 0.0 mandatory**
            (determinism + R7 cost mitigation).
        cache_dir: Cache directory. If ``None`` uses
            :func:`default_cache_dir`. The cache keys by a hash of
            ``(parcel_id, ndvi_curve.tobytes(), prompt_template_version)``.

    Returns:
        Textual description (3-4 sentences) without line breaks.

    Raises:
        ValueError: if ``ndvi_curve`` is empty or has a non-1D shape, or
            if ``temperature`` is not 0.0 (R7: enforced to mitigate cost).
    """
    if ndvi_curve.ndim != 1:
        raise ValueError(f"`ndvi_curve` must be 1D; received shape {ndvi_curve.shape}.")
    if ndvi_curve.size == 0:
        raise ValueError("`ndvi_curve` cannot be empty.")
    if temperature != 0.0:
        raise ValueError("`temperature` must be 0.0 (R7 — determinism + Gemini cost).")

    if doy is None:
        doy = np.linspace(1.0, 365.0, ndvi_curve.size, dtype=np.float64)
    elif doy.shape != ndvi_curve.shape:
        raise ValueError(
            f"`doy` shape {doy.shape} does not match `ndvi_curve` shape {ndvi_curve.shape}."
        )

    # Impute NaN with the mean of the finite values (does not break the prompt).
    clean_curve = ndvi_curve.copy()
    if np.isnan(clean_curve).any():
        finite_mean = float(np.nanmean(clean_curve)) if np.any(~np.isnan(clean_curve)) else 0.0
        clean_curve = np.where(np.isnan(clean_curve), finite_mean, clean_curve)

    cache_dir_resolved = cache_dir if cache_dir is not None else default_cache_dir()
    cache_key = _hash_curve(parcel_id, clean_curve, model)
    cache_file = cache_dir_resolved / f"{cache_key}.json"
    if cache_file.exists():
        try:
            payload = json.loads(cache_file.read_text(encoding="utf-8"))
            description = str(payload["description"]).replace("\n", " ").strip()
            logger.info("phenology_description_cache_hit", parcel_id=parcel_id)
            return description
        except (OSError, KeyError, json.JSONDecodeError) as exc:
            logger.warning(
                "phenology_description_cache_unreadable",
                cache_file=str(cache_file),
                error=str(exc),
            )

    prompt = _build_prompt(clean_curve, doy, crop_type_hint=crop_type_hint)
    client = _get_client()
    raw = client(prompt, model=model, temperature=temperature)
    description = " ".join(raw.split())

    payload = {
        "parcel_id": parcel_id,
        "model": model,
        "temperature": temperature,
        "description": description,
        "crop_type_hint": crop_type_hint,
    }
    try:
        cache_file.parent.mkdir(parents=True, exist_ok=True)
        cache_file.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
    except OSError as exc:  # pragma: no cover
        logger.warning(
            "phenology_description_cache_write_failed",
            cache_file=str(cache_file),
            error=str(exc),
        )
    return description


def encode_descriptions(
    descriptions: Sequence[str],
    *,
    encoder: str = "sentence-transformers",
    model_name: str = DEFAULT_TEXT_ENCODER,
) -> np.ndarray:
    """Encode the descriptions into dense vectors.

    Args:
        descriptions: Sequence of texts to encode.
        encoder: ``"sentence-transformers"`` (default; already in deps) or
            ``"farslip-clip"`` (documented alternative; consumes the
            text-encoder of :class:`FarSLIPExtractor`, **not implemented
            here** — owned by US-017).
        model_name: sentence-transformers model identifier.

    Returns:
        ``(N, D)`` ``np.float32`` matrix. D = ``DEFAULT_TEXT_EMBED_DIM`` for
        the default model.

    Raises:
        NotImplementedError: if ``encoder == "farslip-clip"`` (TODO
        Paper Track / Phase 2 US-022-b).
        ValueError: if ``encoder`` is not one of the supported values.
    """
    if encoder == "farslip-clip":
        raise NotImplementedError(
            "encoder='farslip-clip' not yet implemented; "
            "remains a TODO for the Paper Track. Use 'sentence-transformers'."
        )
    if encoder != "sentence-transformers":
        raise ValueError(
            f"`encoder` must be 'sentence-transformers' or 'farslip-clip'; received {encoder!r}."
        )
    if not descriptions:
        return np.zeros((0, DEFAULT_TEXT_EMBED_DIM), dtype=np.float32)

    try:
        from sentence_transformers import SentenceTransformer
    except ImportError as exc:  # pragma: no cover
        raise ImportError(
            "sentence-transformers is not installed. Run `poetry install --with ml`."
        ) from exc
    model = SentenceTransformer(model_name)
    embeddings = model.encode(
        list(descriptions),
        convert_to_numpy=True,
        normalize_embeddings=True,
        show_progress_bar=False,
    )
    return np.asarray(embeddings, dtype=np.float32)


def build_phenology_text_block(
    parcel_ndvi_frame: pl.DataFrame,
    *,
    ndvi_col_prefix: str = "NDVI_t_",
    parcel_id_col: str = "parcel_id",
    year_col: str = "year",
    crop_hint_col: str | None = None,
    model: str = "gemini-3.5-flash",
    encoder: str = "sentence-transformers",
    cache_dir: Path | None = None,
    max_parcels: int | None = None,
    seed: int = 42,
    skip_llm: bool = False,
    progress_every: int = 100,
) -> pl.DataFrame:
    """Build the ``pheno_text_*`` block ready for LEFT JOIN in ``fusion.py``.

    For each row of ``parcel_ndvi_frame``:
      1. Reconstructs the NDVI curve from ``{ndvi_col_prefix}{i:02d}`` columns
         (or FFT columns if the former do not exist — fallback symmetric
         to that of :class:`TemporalDataset`).
      2. Calls :func:`generate_phenology_description` (mockable in tests
         via :func:`set_llm_client`).
      3. Encodes all descriptions with :func:`encode_descriptions`.

    Args:
        parcel_ndvi_frame: DataFrame with at least ``parcel_id``, ``year`` and
            NDVI curve / FFT coefficients.
        ndvi_col_prefix: Prefix of the T-discrete columns (default
            ``"NDVI_t_"``).
        parcel_id_col: Name of the identifier column.
        year_col: Name of the year column.
        crop_hint_col: Optional column with the crop hint
            (string-like). If ``None`` it is omitted.
        model: LLM model (default ``"gemini-3.5-flash"``).
        encoder: Text-encoder (``"sentence-transformers"`` or
            ``"farslip-clip"``).
        cache_dir: Cache directory (default
            :func:`default_cache_dir`).
        max_parcels: Stratified subsample (D-5 of US-022b-D). ``None``
            = all rows (beware Gemini cost).
        seed: Subsample seed.
        skip_llm: If ``True`` skips the LLM call and generates zero
            embeddings — useful **only in tests**. For use in notebooks /
            pipelines the module raises ``DeprecationWarning`` and requires
            real credentials. The resulting block with ``skip_llm=True``
            has the correct shape but null content (zeros).
        progress_every: Frequency (every N processed parcels) at which a
            structured log is emitted with ``n_done``, ``n_total``,
            ``elapsed_s``, ``eta_s`` and ``est_cost_usd``. Default 100.

    Returns:
        ``pl.DataFrame`` with ``parcel_id``, ``year`` and
        ``pheno_text_000..pheno_text_{D-1}``.

    Raises:
        RuntimeError: if ``skip_llm=False``, there is no client injected via
            :func:`set_llm_client` and there are no Gemini credentials in
            the environment (``GEMINI_API_KEY`` / ``GOOGLE_API_KEY`` /
            ``GOOGLE_GENAI_USE_VERTEXAI``).
    """
    # Hard barrier: forbids running the LLM without credentials or a mocked
    # client. The `no silent mocks or skips` rule applies since
    # US-023-preview v2 (deliverable notebooks).
    if not skip_llm and _LLM_CLIENT is None and not _has_credentials():
        raise RuntimeError(
            "Gemini is not configured. Set GEMINI_API_KEY (or "
            "GOOGLE_API_KEY / GOOGLE_GENAI_USE_VERTEXAI=true + "
            "GOOGLE_CLOUD_PROJECT) in .env.local, or use skip_llm=True "
            "only for testing."
        )
    if skip_llm:
        warnings.warn(
            "build_phenology_text_block(skip_llm=True) genera embeddings "
            "de ceros. Usalo solo en tests: notebooks entregables deben "
            "ejecutar Gemini real.",
            DeprecationWarning,
            stacklevel=2,
        )

    df = parcel_ndvi_frame
    if max_parcels is not None and max_parcels > 0 and df.height > max_parcels:
        df = df.sample(n=max_parcels, seed=seed, with_replacement=False)
        logger.info("pheno_text_block_subsampled", n=df.height)

    parcel_ids = df.get_column(parcel_id_col).to_list()
    years = df.get_column(year_col).to_list() if year_col in df.columns else [None] * df.height
    crop_hints: list[str | None] = (
        df.get_column(crop_hint_col).to_list()
        if crop_hint_col is not None and crop_hint_col in df.columns
        else [None] * df.height
    )

    curves = _extract_ndvi_curves(df, prefix=ndvi_col_prefix)
    descriptions: list[str] = []
    if skip_llm:
        # Generate deterministic placeholder descriptions so the
        # encoder produces reproducible embeddings in CI without network.
        descriptions = [f"placeholder_pheno_{pid}" for pid in parcel_ids]
    else:
        n_total = len(parcel_ids)
        est_total_cost = n_total * COST_PER_DESCRIPTION_USD
        logger.info(
            "phenology_text_block_start",
            n_total=n_total,
            model=model,
            est_total_cost_usd=round(est_total_cost, 4),
        )
        t_start = time.monotonic()
        for idx, (pid, curve, hint) in enumerate(
            zip(parcel_ids, curves, crop_hints, strict=True), start=1
        ):
            descriptions.append(
                generate_phenology_description(
                    curve,
                    parcel_id=pid,
                    crop_type_hint=hint,
                    model=model,
                    temperature=0.0,
                    cache_dir=cache_dir,
                )
            )
            if idx % max(progress_every, 1) == 0 or idx == n_total:
                elapsed_s = time.monotonic() - t_start
                rate = idx / elapsed_s if elapsed_s > 0 else 0.0
                eta_s = (n_total - idx) / rate if rate > 0 else 0.0
                logger.info(
                    "phenology_text_block_progress",
                    n_done=idx,
                    n_total=n_total,
                    elapsed_s=round(elapsed_s, 2),
                    eta_s=round(eta_s, 2),
                    est_cost_usd=round(idx * COST_PER_DESCRIPTION_USD, 4),
                )

    if skip_llm:
        # In skip_llm we return zeros to avoid downloading the
        # sentence-transformers model (test without network or heavy dependencies).
        embeddings = np.zeros((len(descriptions), DEFAULT_TEXT_EMBED_DIM), dtype=np.float32)
    else:
        embeddings = encode_descriptions(descriptions, encoder=encoder)

    text_cols = [f"pheno_text_{i:03d}" for i in range(embeddings.shape[1])]
    block = {
        parcel_id_col: parcel_ids,
        year_col: years,
    }
    for j, col_name in enumerate(text_cols):
        block[col_name] = embeddings[:, j].tolist()
    schema: dict[str, pl.DataType] = {
        parcel_id_col: df.schema[parcel_id_col],
        year_col: df.schema.get(year_col, pl.Int16()),
    }
    for col_name in text_cols:
        schema[col_name] = pl.Float32()
    return pl.DataFrame(block, schema=schema)


