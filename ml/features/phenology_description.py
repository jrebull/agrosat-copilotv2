#: LLM client signature: ``(prompt, *, model, temperature) -> str``.
LlmClient = Callable[..., str]


_LLM_CLIENT: LlmClient | None = None


def set_llm_client(client: LlmClient | None) -> None:
    """Inject a custom LLM client (primary use: mocked tests).

    Args:
        client: Callable ``(prompt: str, *, model: str, temperature: float)
            -> str``. Pass ``None`` to restore the LiteLLM/Vertex AI default.
    """
    global _LLM_CLIENT
    _LLM_CLIENT = client


def _default_litellm_client(prompt: str, *, model: str, temperature: float) -> str:
    """Gemini 3.5 Flash client via LiteLLM (provider-agnostic fallback).

    Lazy import: only needed at runtime and only if there is no client
    injected via ``set_llm_client``. In CI/tests there is ALWAYS a mock.
    """
    try:
        import litellm
    except ImportError as exc:  # pragma: no cover
        raise ImportError(
            "litellm is not installed. Run `poetry install --with ml`. "
            "Alternatively inject a client with `set_llm_client(...)`."
        ) from exc

    response = litellm.completion(  # type: ignore[attr-defined]
        model=model if "/" in model else f"vertex_ai/{model}",
        messages=[{"role": "user", "content": prompt}],
        temperature=temperature,
        max_tokens=512,
    )
    # LiteLLM normalizes the response to OpenAI format.
    content = response["choices"][0]["message"]["content"]
    return str(content).strip()


def _model_supports_thinking_level(model: str) -> bool:
    """Whether ``model`` accepts the ``thinking_level`` config field.

    Only Gemini 3.x models support it; 2.x models (and others) return
    ``400 Thinking level is not supported for this model``. Matches the
    major version after the ``gemini-`` prefix (e.g. ``gemini-3.5-flash`` ->
    True, ``gemini-2.5-flash-lite`` -> False).

    Args:
        model: Model identifier.

    Returns:
        ``True`` for ``gemini-3.x`` models, ``False`` otherwise.
    """
    name = model.lower().removeprefix("models/")
    if not name.startswith("gemini-"):
        return False
    version = name[len("gemini-") :]
    major = version.split(".", 1)[0].split("-", 1)[0]
    return major.isdigit() and int(major) >= 3


def _has_credentials() -> bool:
    """Check whether Gemini credentials are configured in the environment.

    Detects any of the following auth options (order not relevant):

    - ``GEMINI_API_KEY``: public Google AI Studio API.
    - ``GOOGLE_API_KEY``: historical alias of the public API.
    - ``GOOGLE_GENAI_USE_VERTEXAI=true``: Vertex AI mode with the
      environment SA (Cloud Run, Vertex Workbench, etc.).
    - ``GOOGLE_CLOUD_PROJECT``: defined GCP project (sufficient when
      combined with ADC / implicit SA).

    Returns:
        ``True`` if at least one credential is present with a non-empty
        value. ``False`` if all are absent or empty.
    """
    for var in _CREDENTIAL_ENV_VARS:
        value = os.environ.get(var, "").strip()
        if value and value.lower() not in {"false", "0"}:
            return True
    return False


def _default_google_genai_client(prompt: str, *, model: str, temperature: float) -> str:
    """Native Gemini 3.5 Flash client via the google-genai SDK.

    More efficient than LiteLLM for this case: it supports ``thinking_level``
    (default ``"minimal"`` for low latency on short descriptions) and
    allows structured output with ``response_json_schema``. For now we
    return plain text for compatibility with the ``LlmClient`` contract;
    structured output is left ready for
    ``build_phenology_text_block_structured`` (next iteration).

    Auth:
      - Vertex AI (preferred): export ``GOOGLE_GENAI_USE_VERTEXAI=true`` +
        ``GOOGLE_CLOUD_PROJECT=...`` + ``GOOGLE_CLOUD_LOCATION=us-central1``.
        Uses the environment SA (Cloud Run, Vertex AI Workbench, etc.).
      - Public Gemini API: export ``GEMINI_API_KEY=...`` (or ``GOOGLE_API_KEY``).

    Lazy import of the SDK; tests use ``set_llm_client`` with a mock.

    Args:
        prompt: Text of the 3-block prompt (Wen et al. 2025 Fig. 2).
        model: Model identifier, default ``"gemini-3.5-flash"``.
        temperature: Determinism. ``0.0`` for a stable per-parcel cache.

    Returns:
        Plain text of the generated phenology description.
    """
    try:
        from google import genai  # type: ignore[import-not-found]
        from google.genai import types  # type: ignore[import-not-found]
    except ImportError as exc:  # pragma: no cover
        raise ImportError(
            "google-genai is not installed. Run `poetry add google-genai`. "
            "Alternatively use the LiteLLM client (fallback) or inject a "
            "mock with `set_llm_client(...)`."
        ) from exc

    # `Client()` auto-detects Vertex AI vs public API from env vars. A
    # client-side HTTP timeout (60s) is MANDATORY for long batches: without it a
    # single stuck socket hangs the worker thread indefinitely (and, with a
    # completion-gated flush, the whole job) -- observed on the 69k run when the
    # API got flaky. On timeout the call raises and the retry loop below kicks in.
    client = genai.Client(http_options=types.HttpOptions(timeout=_HTTP_TIMEOUT_MS))
    # `thinking_level` is a Gemini 3.x feature: 3.x accepts "minimal" to cut
    # latency on short descriptions, but 2.x models (e.g. gemini-2.5-flash-lite)
    # reject it with `400 Thinking level is not supported for this model`. Apply
    # it only for 3.x; the numeric `thinking_budget` was deprecated per the 3.5
    # docs, so 2.x runs with the default thinking config.
    thinking_config = (
        types.ThinkingConfig(thinking_level="minimal")
        if _model_supports_thinking_level(model)
        else None
    )
    config = types.GenerateContentConfig(
        temperature=temperature,
        max_output_tokens=512,
        thinking_config=thinking_config,
    )

    # Retry with capped exponential backoff for 429 / 503 / timeout. Six
    # attempts (~2+4+8+16+30+30s) before propagating: a single 69k-parcel batch
    # would otherwise die on a SUSTAINED 503 spike (observed at peak hours) when
    # only 3 short retries were allowed. The cap keeps the backoff from exploding.
    max_attempts = 6
    base_delay = 2.0
    max_delay = 30.0
    last_exc: Exception | None = None
    for attempt in range(max_attempts):
        try:
            response = client.models.generate_content(
                model=model,
                contents=prompt,
                config=config,
            )
            return str(response.text or "").strip()
        except Exception as exc:  # pragma: no cover - depends on the API.
            message = str(exc)
            is_transient = (
                "429" in message
                or "503" in message
                or "rate limit" in message.lower()
                or "unavailable" in message.lower()
                or "timeout" in message.lower()
                or "timed out" in message.lower()
            )
            last_exc = exc
            if not is_transient or attempt == max_attempts - 1:
                raise
            delay = min(base_delay * (2**attempt), max_delay)
            logger.warning(
                "phenology_description_gemini_retry",
                attempt=attempt + 1,
                max_attempts=max_attempts,
                delay_s=delay,
                error=message[:200],
            )
            time.sleep(delay)
    # Only reachable if the loop exits due to exhaustion without raise (should not happen).
    raise RuntimeError(  # pragma: no cover
        f"Gemini exhausted all {max_attempts} retries."
    ) from last_exc


def _get_client() -> LlmClient:
    """Return the active client according to the order:

    1. Client injected via ``set_llm_client`` (tests always use it).
    2. Native ``google-genai`` client if the env var ``AGROSAT_LLM_PROVIDER``
       is ``"google-genai"`` or if ``google-genai`` is installed and no
       other is forced.
    3. LiteLLM fallback (provider-agnostic).
    """
    import os

    if _LLM_CLIENT is not None:
        return _LLM_CLIENT

    provider = os.environ.get("AGROSAT_LLM_PROVIDER", "").strip().lower()
    if provider == "google-genai":
        return _default_google_genai_client
    if provider == "litellm":
        return _default_litellm_client

    # Auto: prefer google-genai if available (faster); LiteLLM
    # as a transparent fallback.
    try:
        import google.genai  # noqa: F401

        return _default_google_genai_client
    except ImportError:
        return _default_litellm_client


