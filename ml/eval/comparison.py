def _train_scenario_model(
    scenario_df: pl.DataFrame,
    *,
    model_kind: str,
    k_folds: int,
    buffer_km: float,
    random_state: int,
) -> tuple[dict[str, float], float]:
    """Train a model over a scenario and measure the wall-clock of the fit.

    Reuses :func:`ml.train.baseline.train_one_model` (same spatial CV as the rest
    of the baseline, decision D3). The import is deferred to avoid the circular
    import with ``ml.eval.__init__``.

    Args:
        scenario_df: DataFrame of the already aligned scenario.
        model_kind: ``"rf"``, ``"xgb"`` or ``"lgbm"``.
        k_folds: Number of folds of the spatial CV.
        buffer_km: Anti-leakage buffer in km.
        random_state: Deterministic seed.

    Returns:
        Tuple ``(metrics, train_time_s)`` with the out-of-fold metrics of the
        baseline and the wall-clock of the final ``fit`` (decision D4).
    """
    # Deferred import: breaks the cycle `baseline -> eval.metrics` /
    # `eval.__init__ -> comparison`.
    from ml.train.baseline import train_one_model

    start = time.perf_counter()
    result = train_one_model(
        scenario_df,
        model=model_kind,  # type: ignore[arg-type]
        k_folds=k_folds,
        buffer_km=buffer_km,
        random_state=random_state,
    )
    train_time_s = time.perf_counter() - start
    return result.metrics, train_time_s


def _count_features(scenario_df: pl.DataFrame) -> int:
    """Count the numeric columns usable as features of a scenario.

    Excludes the metadata (``_META_COLS``) and the non-numeric columns.

    Args:
        scenario_df: DataFrame of the scenario.

    Returns:
        Number of feature columns.
    """
    return sum(
        1
        for col in scenario_df.columns
        if col not in _META_COLS
        and not col.endswith(_META_SUFFIXES)
        and scenario_df.schema[col].is_numeric()
    )


def _best_scenario(table: pl.DataFrame) -> str:
    """Return the scenario with the highest ``f1_macro`` of the table.

    Args:
        table: Comparison table of 9 rows.

    Returns:
        The human-readable name of the winning scenario (best of its 3 models).
    """
    top_row = table.sort("f1_macro", descending=True).row(0, named=True)
    return str(top_row["scenario"])


def _alphaearth_delta(table: pl.DataFrame) -> float:
    """Compute the ``f1_macro`` delta of AlphaEarth vs raw Sentinel-2.

    Compares the best model of the AlphaEarth scenario with the best of raw
    Sentinel-2. Quantifies the incremental value of the embedding.

    Args:
        table: Comparison table of 9 rows.

    Returns:
        ``f1_macro(AlphaEarth) - f1_macro(raw S2)``; positive if the embedding
        contributes. ``nan`` if any of the two scenarios is missing.
    """
    ae_label = _SCENARIO_LABELS["alphaearth"]
    s2_label = _SCENARIO_LABELS["s2_raw"]
    ae_rows = table.filter(pl.col("scenario") == ae_label)
    s2_rows = table.filter(pl.col("scenario") == s2_label)
    if ae_rows.height == 0 or s2_rows.height == 0:
        return float("nan")
    ae_best = float(ae_rows.get_column("f1_macro").max())  # type: ignore[arg-type]
    s2_best = float(s2_rows.get_column("f1_macro").max())  # type: ignore[arg-type]
    return ae_best - s2_best


def _column_dtype(column: str) -> pl.DataType:
    """Return the Polars dtype of a column of the comparison table.

    Args:
        column: Name of the column.

    Returns:
        The corresponding :class:`polars.DataType`.
    """
    if column in ("scenario", "model"):
        return pl.Utf8()
    if column == "n_features":
        return pl.Int64()
    return pl.Float64()


