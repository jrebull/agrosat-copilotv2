def _load_scenario(path: str | Path) -> pl.DataFrame:
    """Load a scenario parquet from disk.

    Args:
        path: Path to the scenario parquet.

    Returns:
        The raw Polars DataFrame.

    Raises:
        FileNotFoundError: if the parquet does not exist.
        ValueError: if it lacks ``parcel_id`` or ``class_id``.
    """
    resolved = Path(path)
    if not resolved.exists():
        raise FileNotFoundError(
            f"Scenario parquet not found at {resolved}. "
            "Generate scenario (b) with `make s2-raw-parcels` or verify the "
            "AlphaEarth / feature_selection paths."
        )
    df = pl.read_parquet(resolved)
    for col in ("parcel_id", "class_id"):
        if col not in df.columns:
            raise ValueError(f"The parquet {resolved} must contain the column `{col}`.")
    return df


def _align_scenarios_by_parcel(
    scenarios: dict[str, pl.DataFrame],
) -> dict[str, pl.DataFrame]:
    """Align the scenarios by ``parcel_id`` with an *inner join* (D2).

    Computes the intersection of ``parcel_id`` present in the three scenarios and
    filters each DataFrame to that common set, sorted deterministically.
    Guarantees that the three models are evaluated over exactly the same set of
    parcels and the same spatial folds.

    Args:
        scenarios: Map ``{key: DataFrame}`` of the raw scenarios.

    Returns:
        Map ``{key: DataFrame}`` with the three frames filtered to the common
        ``parcel_id`` and sorted by ``parcel_id``.

    Raises:
        ValueError: if the intersection of ``parcel_id`` is empty.
    """
    common: set[str] | None = None
    for df in scenarios.values():
        ids = set(df.get_column("parcel_id").cast(pl.Utf8).to_list())
        common = ids if common is None else common & ids
    if not common:
        raise ValueError(
            "The inner join by `parcel_id` of the 3 scenarios is empty: "
            "the parquets do not share parcels."
        )

    common_sorted = sorted(common)
    keep = pl.DataFrame({"parcel_id": common_sorted})
    aligned: dict[str, pl.DataFrame] = {}
    for key, df in scenarios.items():
        normalized = df.with_columns(pl.col("parcel_id").cast(pl.Utf8))
        # Inner join against the common set + deterministic order: the three
        # frames end up with the same rows in the same order.
        joined = (
            keep.join(normalized, on="parcel_id", how="inner")
            .unique(subset="parcel_id", keep="first")
            .sort("parcel_id")
        )
        aligned[key] = joined

    logger.info(
        "scenarios_aligned",
        n_common=len(common_sorted),
        scenarios=sorted(scenarios),
    )
    return aligned


def _subsample_aligned(
    aligned: dict[str, pl.DataFrame],
    max_samples: int,
    random_state: int,
) -> dict[str, pl.DataFrame]:
    """Subsample the aligned scenarios in a class-stratified way.

    Selects the same set of ``parcel_id`` for the three scenarios (keeps the D2
    alignment). Useful for dev/CI with ``max_samples``.

    Args:
        aligned: Map of scenarios already aligned by ``parcel_id``.
        max_samples: Target size of the subsample.
        random_state: Deterministic seed.

    Returns:
        Map of scenarios subsampled to the same set of parcels.
    """
    reference = next(iter(aligned.values()))
    if reference.height <= max_samples:
        return aligned

    frac = max_samples / reference.height
    sampled_ids = (
        reference.select(["parcel_id", "class_id"])
        .filter(pl.col("class_id").is_not_null())
        .group_by("class_id", maintain_order=True)
        .map_groups(
            lambda g: g.sample(
                n=max(1, round(g.height * frac)),
                seed=random_state,
            )
        )
        .get_column("parcel_id")
    )
    keep = pl.DataFrame({"parcel_id": sampled_ids})
    return {
        key: keep.join(df, on="parcel_id", how="inner").sort("parcel_id")
        for key, df in aligned.items()
    }


