"""Tabular baseline scenario comparison (US-022, EPIC 4).

Module of the last US of EPIC 4 (Avance 3). Trains Random Forest and XGBoost
over **three views** of the same set of PASTIS-R parcels and builds the
comparison table that supports the "Metric" criterion of Avance 3:

- **(a) AlphaEarth 64-dim** — the ``dim_00..dim_63`` embedding of the AlphaEarth
  Foundations Foundation Model.
- **(b) Raw Sentinel-2** — the 10 bands ``B02..B12`` averaged temporally and
  spatially per parcel (generated by ``scripts/build_s2_raw_parcels.py``).
- **(c) Combined vector** — the 187 spectro-temporal features of EPIC 3
  (US-018).

Canonical decisions (plan ``docs/us-planning/us-022.md`` 2.1):

- **D2**: the 3 views are aligned by ``parcel_id`` with an *inner join* so the
  comparison is fair (same set of parcels).
- **D3**: the spatial CV is 5-fold and is reused for the 3 scenarios via
  :func:`ml.train.baseline._build_cv_splits` (cached). ZERO random ``KFold``.
- **D4**: ``train_time_s`` is the wall-clock of the final ``fit`` over the whole
  scenario.
- **D7**: the LaTeX export uses ``df.to_pandas().to_latex()`` isolated in
  :func:`export_comparison_latex` — the only use of pandas in the module,
  encapsulated as presentation I/O.

``ml.train.baseline`` is imported **lazily** inside the functions to break the
import cycle: ``baseline`` imports from ``ml.eval.metrics`` and
``ml.eval.__init__`` re-exports this module — a module-level import would trigger
a circular import when loading the ``ml.eval`` package.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

import polars as pl
import structlog

if TYPE_CHECKING:
    from matplotlib.figure import Figure

logger = structlog.get_logger(__name__)

__all__ = [
    "ComparisonResult",
    "build_comparison_table",
    "build_fold5_comparison_table",
    "export_comparison_latex",
    "fold5_barplot_figure",
]

# Canonical order of the scenarios (short label -> human-readable name).
_SCENARIO_LABELS: dict[str, str] = {
    "alphaearth": "AlphaEarth 64-dim",
    "s2_raw": "Sentinel-2 crudo (10 bandas)",
    "combined": "Vector combinado (187 feat)",
}

# Models of the comparison, in table order. The three tabular baselines
# are evaluated to capture differences between families (bagging vs
# classic boosting vs histogram-based boosting).
_MODEL_KINDS: tuple[str, ...] = ("rf", "xgb", "lgbm")

# Metadata columns that are NOT features (excluded when counting
# `n_features`). Mirror of `ml.train.baseline._META_COLS` plus the extra
# columns the scenario parquets carry along.
_META_COLS: frozenset[str] = frozenset(
    {
        "parcel_id",
        "year",
        "patch_id",
        "instance_id",
        "class_id",
        "class_name",
        "fold",
        "n_pixels",
        "area_m2",
        "geometry",
    }
)

# Column suffixes that are never features (defense in depth over
# `_META_COLS`: the US-023-preview-v2 bug slipped in with `patch_id_right` when
# `load_features_dataset_with_meta` did a left join without filtering overlaps).
_META_SUFFIXES: tuple[str, ...] = ("_right", "_left", "_x", "_y")

# Column order of the final comparison table.
_TABLE_COLUMNS: tuple[str, ...] = (
    "scenario",
    "model",
    "n_features",
    "f1_macro",
    "f1_weighted",
    "miou",
    "train_time_s",
)


# ---------------------------------------------------------------------------
# Output dataclass.
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ComparisonResult:
    """Result of the baseline scenario comparison.

    Attributes:
        table: ``pl.DataFrame`` with 9 rows (3 scenarios x 3 models) and columns
            ``(scenario, model, n_features, f1_macro, f1_weighted, miou,
            train_time_s)``, sorted by ``f1_macro`` descending.
        best_scenario: Human-readable name of the scenario with the highest
            ``f1_macro`` (over the best of its three models).
        alphaearth_delta: Delta of ``f1_macro`` of the pure AlphaEarth scenario
            against raw Sentinel-2 (best model of each). Quantifies the
            incremental value of the embedding; positive if AlphaEarth beats raw
            S2.
        n_parcels: Number of effective parcels after the *inner join* of the 3
            scenarios (decision D2).
    """

    table: pl.DataFrame
    best_scenario: str
    alphaearth_delta: float
    n_parcels: int


