def build_comparison_table(
    scenario_paths: dict[str, str | Path],
    *,
    k_folds: int = 5,
    buffer_km: float = 1.0,
    max_samples: int = 0,
    random_state: int = 42,
) -> ComparisonResult:
    """Train RF+XGB+LGBM over 3 scenarios with the same spatial CV.

    Loads the three scenario parquets, aligns them by ``parcel_id`` with an
    *inner join* (decision D2) so the three models see exactly the same set of
    parcels, and trains Random Forest, XGBoost and LightGBM over each view
    reusing :func:`ml.train.baseline.train_one_model` (same 5-fold spatial CV,
    decision D3).

    Args:
        scenario_paths: Map ``{"alphaearth": path, "s2_raw": path,
            "combined": path}``. The three keys are mandatory; each parquet must
            contain ``parcel_id`` and ``class_id``.
        k_folds: Number of folds of the spatial CV (default 5).
        buffer_km: Anti-leakage buffer in km between folds (default 1.0).
        max_samples: Class-stratified subsample for dev/CI (``0`` = complete
            dataset).
        random_state: Deterministic seed.

    Returns:
        A :class:`ComparisonResult` with the table of 9 rows (3 models x 3
        scenarios), the winning scenario and the ``f1_macro`` delta of AlphaEarth
        vs raw S2.

    Raises:
        ValueError: if any of the three scenario keys is missing or if the
            *inner join* leaves the set of parcels empty.
        FileNotFoundError: if any of the parquets does not exist.
    """
    missing = set(_SCENARIO_LABELS) - set(scenario_paths)
    if missing:
        raise ValueError(
            f"`scenario_paths` must contain the keys {sorted(_SCENARIO_LABELS)}; "
            f"missing {sorted(missing)}."
        )

    raw_scenarios = {key: _load_scenario(scenario_paths[key]) for key in _SCENARIO_LABELS}
    aligned = _align_scenarios_by_parcel(raw_scenarios)
    n_parcels = next(iter(aligned.values())).height

    if max_samples > 0:
        aligned = _subsample_aligned(aligned, max_samples, random_state)
        logger.info(
            "comparison_subsampled",
            max_samples=max_samples,
            n_parcels=next(iter(aligned.values())).height,
        )

    logger.info(
        "comparison_table_start",
        n_parcels=n_parcels,
        n_effective=next(iter(aligned.values())).height,
        k_folds=k_folds,
    )

    rows: list[dict[str, object]] = []
    for scenario_key, label in _SCENARIO_LABELS.items():
        scenario_df = aligned[scenario_key]
        n_features = _count_features(scenario_df)
        for model_kind in _MODEL_KINDS:
            metrics, train_time_s = _train_scenario_model(
                scenario_df,
                model_kind=model_kind,
                k_folds=k_folds,
                buffer_km=buffer_km,
                random_state=random_state,
            )
            rows.append(
                {
                    "scenario": label,
                    "model": model_kind.upper(),
                    "n_features": n_features,
                    "f1_macro": round(metrics["f1_macro"], 4),
                    "f1_weighted": round(metrics["f1_weighted"], 4),
                    "miou": round(metrics["miou"], 4),
                    "train_time_s": round(train_time_s, 3),
                }
            )
            logger.info(
                "comparison_cell_done",
                scenario=scenario_key,
                model=model_kind,
                f1_macro=round(metrics["f1_macro"], 4),
                train_time_s=round(train_time_s, 2),
            )

    table = pl.DataFrame(rows, schema={c: _column_dtype(c) for c in _TABLE_COLUMNS})
    table = table.sort("f1_macro", descending=True)

    best_scenario = _best_scenario(table)
    alphaearth_delta = _alphaearth_delta(table)
    logger.info(
        "comparison_table_done",
        best_scenario=best_scenario,
        alphaearth_delta=round(alphaearth_delta, 4),
        n_parcels=n_parcels,
    )
    return ComparisonResult(
        table=table,
        best_scenario=best_scenario,
        alphaearth_delta=alphaearth_delta,
        n_parcels=n_parcels,
    )


def export_comparison_latex(
    result: ComparisonResult,
    path: str | Path,
) -> Path:
    """Export the comparison table to LaTeX (booktabs) for the Paper Track.

    Generates a ``booktabs``-style LaTeX fragment ready for ``\\input{}`` in the
    paper. Polars does not export native LaTeX: the conversion uses
    ``df.to_pandas().to_latex()`` — the **only** use of pandas in the module,
    isolated here as presentation I/O (decision D7).

    Args:
        result: The :class:`ComparisonResult` to export.
        path: Destination path of the ``.tex`` file.

    Returns:
        The :class:`~pathlib.Path` of the written ``.tex``.
    """
    out_path = Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    # Only pandas use in the module (D7): presentation conversion.
    pandas_df = result.table.to_pandas()
    body = pandas_df.to_latex(
        index=False,
        escape=True,
        column_format="llrrrrr",
        caption=(
            "Comparativa del baseline tabular sobre tres escenarios de "
            f"features (PASTIS-R, {result.n_parcels} parcelas, CV espacial "
            "5-fold). Escenario ganador: "
            f"{result.best_scenario}; delta F1-macro AlphaEarth vs "
            f"Sentinel-2 crudo: {result.alphaearth_delta:+.4f}."
        ),
        label="tab:baseline-comparison",
        float_format="%.4f",
    )
    out_path.write_text(body, encoding="utf-8")
    logger.info("comparison_latex_written", path=str(out_path))
    return out_path


